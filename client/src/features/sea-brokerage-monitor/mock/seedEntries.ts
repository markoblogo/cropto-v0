interface SeedEntryDefinition {
  id: string;
  createdAt: string;
  brokerProfileId: string;
  type: "bid" | "offer";
  commodity: CommodityCode;
  gradeOrSpec: string;
  volumeFrom: number;
  volumeTo: number;
  basis: Basis;
  destinationPortCode: string;
  destinationCountryCode: string;
  periodType: PeriodType;
  periodLabel: string;
  periodStart: string | null;
  periodEnd: string | null;
  priceFrom: number | null;
  priceTo: number | null;
  currency: Currency;
  transportType: TransportType;
  note: string | null;
  telegramRelayStatus?: TelegramRelayStatus;
}

function getBrokerProfile(brokerProfileId: string) {
  const profile = brokers.find((broker) => broker.id === brokerProfileId);
  if (!profile) {
    throw new Error(`Unknown broker profile id: ${brokerProfileId}`);
  }

  return brokerProfilesByAuthUserId[profile.authUserId] ?? profile;
}

function getCountryLabel(countryCode: string) {
  const option = countryOptions.find((country) => country.code === countryCode);
  return option?.label ?? countryCode;
}

function getPortLabel(portCode: string) {
  const option = portOptions.find((port) => port.code === portCode);
  return option?.label ?? portCode;
}

function createSeedEntry(definition: SeedEntryDefinition): BrokerageEntry {
  const createdBy = getBrokerProfile(definition.brokerProfileId);
  const commodityLabel = commodityOptionMap[definition.commodity]?.label ?? definition.commodity;

  const baseEntry: Omit<BrokerageEntry, "canonicalView"> = {
    id: definition.id,
    type: definition.type,
    brokerId: createdBy.id,
    brokerCode: createdBy.brokerCode,
    brokerName: createdBy.brokerName,
    companyName: createdBy.companyName,
    commodity: definition.commodity,
    commodityLabel,
    gradeOrSpec: definition.gradeOrSpec,
    volumeFrom: definition.volumeFrom,
    volumeTo: definition.volumeTo,
    volumeUnit: "mt",
    basis: definition.basis,
    destinationPort: getPortLabel(definition.destinationPortCode),
    destinationCountry: getCountryLabel(definition.destinationCountryCode),
    periodType: definition.periodType,
    periodLabel: definition.periodLabel,
    periodStart: definition.periodStart,
    periodEnd: definition.periodEnd,
    priceFrom: definition.priceFrom,
    priceTo: definition.priceTo,
    currency: definition.currency,
    transportType: definition.transportType,
    note: definition.note,
    createdAt: definition.createdAt,
    createdBy,
    telegramRelayStatus: definition.telegramRelayStatus ?? "published",
    telegramRelayMessage: null,
  };

  const entry: BrokerageEntry = {
    ...baseEntry,
    canonicalView: buildCanonicalView(baseEntry),
  };

  return {
    ...entry,
    telegramRelayMessage: formatTelegramRelayMessage(entry),
  };
}

